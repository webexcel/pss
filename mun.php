						<p style="text-align:justify;"><b>PSMUN - CLARION 2023</b></p>
						<p>On the 9th and 10th of November, the school organised the Xth Edition of Clarion PSMUN". We hosted over 325 students from 25+ schools across the city. Ms. Zoe Swinson, Press Officer Diplomat of the US Consulate General graced the inaugurationfunction and spoke to the participants about the role played by MUN conferences in her career and urged the students to move out of their comfort zones.</p> 
