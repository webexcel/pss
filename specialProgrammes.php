					<p><b>Manipal Biomachines</b></p>
					<p>Radha Pss: We, the students of class 12 B, attended an extremely informative session with Anirudh Saravanan on the 16th of August, 2024. An alumni of our school who is currently pursuing  Biotechnology in Manipal Institute of Technology. We were introduced to the concept of Synthetic Biotechnology, (synbio), and its various facets that involved the use of microbiology, genomics, and engineering. </p>
					<p>Further, we learnt about the common jargon used in synbio, such as:<p>
					<ul>
					<li>➔	PCR - Polymerase Chain Reaction </li>
					<li>➔	Plasmids</li>
					<li>➔	Gene Modelling & Prototyping</li>
					<li>➔	Recombination</li>
					</ul>
					We shifted our discussions towards the difference between hybridisation and genetic modification, and the common public’s perception towards Genetically Modified Organisms. The binary debate between the advantages & disadvantages of GMOs eventually lead us to the topic of Bio Ethics, and the various segments of the field: 
					<ul>
					<li>➔	 Medical Ethics</li>
					<li>➔	Environmental Ethics</li>
					<li>➔	Reproductive Ethics</li>
					<li>➔	Research Ethics</li>
					</ul>
					<p>We learnt about the various projects undertaken by the Manipal BioMachines Team, such as the prevention of Vibriosis disease in the local fish population using synthetic biotechnology. </p>
					<p>Recently, the Manipal BioMachines Team has undertaken a project to prevent Coffee Leaf Rust, caused by the fungus Hemileia Vastatrix. The disease is a major source of environmental damage and industrial loss. Prevention of this plant disease can be done by modifying soil microbiota, and introducing the antifungal protein Iturin A. </p>
					<p>In conclusion, the interactive session enabled us to understand the various roles of biology in the field of technology and widened our scope in thinking of future pursuits in Biology and the life sciences.</p>
					
