						<p style="text-align:justify;"><b>CLARION PS MUN 2024</b></p>
						<p>On the 29th and 30th of October, the 11th Edition of Clarion PSMUN brought together 320 students from 14 schools, with Mr. Sriram Iyer, Founder of Nalandaway Foundation, as the esteemed Chief Guest for the inauguration. In his address, Mr. Iyer spoke to the participants about hope and gave inspiring real-life anecdotes.</p>

						<p>This year’s conference featured pressing global topics, including Debt Trap Diplomacy, LTTE issues, and Citizenship Laws, alongside notable simulations in the Kremlin Senate and UNAOC (United Nations Alliance of Civilizations). These discussions allowed delegates to navigate complex geopolitical and social issues, enhancing their analytical and oratory skills.</p>

						<p>The valedictory ceremony, presided over by author and research scholar Mr. Vishal Vasanth, recognized the students’ efforts, applauding their commitment to the conference. DAV Boys Gopalapuram emerged as the Winners of this edition of the conference. PSMUN 2024 continued the tradition of fostering young leaders, marking another impactful year in our MUN legacy.</p>
												
