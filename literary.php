					<p><b>19-07-2023</b></p>
						</p>On the occasion of PS Litt Fest, a week-long celebration of literature-based competitions and lectures, the keynote address was delivered by the school Chairman Sri P C Ramakrishna, a renowned theatre and voice artist on the topic “Relevance of Shakespeare after 500 years” at the Dakshinamoorthy Auditorium on 19th July 2023. students of classes 11 and 12 enthusiastically gathered to immerse themselves in the timeless charm . The speaker’s  iconic baritone voice resonated across the halls, extolling the enduring relevance of the Bard’s literary works. The students were thoroughly captivated and were enriched by how the poet’s verses continue to guide us through today’s tempestuous times, and provide an invaluable lens through which we can view the world. </p>
