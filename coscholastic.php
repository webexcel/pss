						<p><b>Pennum Pannum – Season 2</b></p>
						<p>Celebrating the women composers and contribution of women to carnatic music is the concept behind a very novel initiative by accomplished popular carnatic vocalist Vidwan Saketharaman. Pennum Pannum –season 2 was a grand programme ,held at Narada Gana sabha, Main Hall on June 25. The event was presided over by Chief guests Padmasri Nartaki Nataraj , Kalaimamani Lalgudi Vijayalakshmi and Dr.Akhila Srinivasan. Saketharaman’s Samuditha Foundation with a motto- carnatic music for all, has been teaching carnatic music to over 250 students currently through his Kalashiksha school. The Foundation honoured Padmasri Dandamudi Sumathi Rama Mohan Rao, with the Samuditha Award of Excellence. She is the First Lady mridangam artiste to be conferred “A Top” by All India Radio.</p>

