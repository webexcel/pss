						<p><b>PS CODESSY 2024</b></p>
						
						<p>The 2nd edition of our school’s annual computer science fest – Codessey was held on 20th November 2024. An upgrade from the inaugural edition, this year’s fest consisted of five events, viz., Potpourri, Tech Trivia and Sprint Interview, along with Binary Blitz and Codefusion that were part of the inaugural edition.</p> 
						<p>As Codessey 2.0 was officially declared open by our Principal, Dr. Revathy Parameswaran, it was exhilarating to see participants from twelve city schools delve into the world of technology and coding.</p> 
						<p>The Binary Blitz event was a race against time – an overwhelming 21 teams participating, of which, a mere 8 would go through to the next round, completing programming problems integrated with mathematical concepts.</p> 
						<p>Another exciting event was the Sprint Interview; a real-life experience where participants had to prepare their resume and were interviewed on various topics like AI, Data Science, Machine Learning, etc. </p>
						<p>Codefusion, the classic app-designing event, emulated its success in the inaugural edition. Tech Trivia, a quiz on computer science, technology and applications, consisted of a preliminary written round followed by a buzzer round that made the event edgy. Potpourri was well received by participants; the rounds followed a game-like structure, with the first round based on dumb charades, the second on taboo and the third one ‘heads up’, where participants would hold up a placard on their heads and their team-mates would have to make the participant guess it.</p> 
						<p>As part of the fest, the chief guest, Dr. Madhavan Mukund, Director, Chennai Mathematical Institute presented an enlightening lecture on Computational thinking focusing on search algorithms.  The event concluded with the prize distribution ceremony.  The overall trophy was bagged by PSBB KK Nagar.</p>				
											
