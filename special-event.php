						<p><b>Sciencillatons 2024</b></p>
						
						<p>From October 22 to 23, 2024, our school proudly hosted the Sciencillatons, an inter-school science competition that welcomed students from classes 9 to 12 across Chennai schools. Organized by our dedicated 12th-grade science students and supported by the science faculty, the event aimed to inspire a deeper appreciation for science, technology, and innovation in enhancing human life and environmental sustainability.</p>
