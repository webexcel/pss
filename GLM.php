						 <p id="2"><b>Graduation Ceremony - GLPSS program</p>
							<p style="text-align:justify;">The graduation ceremony of the GLPSS program on Management and Entrepreneurship for the class of 2024 took place on 24th July. The chief guest Dr. Sudhakar V Balachandran - the associate professor and director of MBA Graduate Studies, University of Illinois at Chicago USA, and the director of Great Lakes Institute of Management, India - gave us the honor of having his presence on this occasion.</p>
							<p style="text-align:justify;">Our principal Dr. Revathy Parameswaran gave the welcome address which followed with the introductory remarks given by Dr. Sudhakar V Balachandran. He addressed the students and gave a captivating speech about following our passion. Dr. Suresh Ramanadhan - Dean and Principal of the Great Lakes Institute of Management, Chennai - surprised us with his visit and addressed the audience about the course.</p>
							<p style="text-align:justify;">Out of 60 students who attended the program, 19 of them received special mention and Amazon vouchers for their outstanding performance in the course.</p>
							<p style="text-align:justify;">Three students - P Hayati, Gayathri M and Anirudh Kumaran - addressed the gathering to speak on behalf of all the students about their experience at the Great Lakes campus.</p>						
