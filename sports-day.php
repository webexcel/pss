					<p><b>PS Senior Secondary School Celebrates 50th Sports Day</b></p>
					<div class=" col-xs-12 col-sm-12 col-md-12">
						<p style="text-align:justify;">PS Senior Secondary School celebrated its 50th Sports Day on 16 August 2026 at the Jawaharlal Nehru Stadium with great enthusiasm and sporting spirit. The day began early with the preliminaries and heats for various track and field events. The formal celebration commenced at 2.30 p.m. with Tamil Thai Vazhthu, followed by a prayer. The principal Dr Revathy Parameswaran, welcomed the gathering and introduced the Chief Guest, V. Devarajan, Olympian Boxer, Arjuna Awardee and World Cup Medalist.</p>
						<p style="text-align:justify;">The colourful march past by the four houses—Ruby, Emerald, Sapphire and Topaz—was a splendid display of discipline, coordination and perfect synchronization. Champions from various sporting events carried the Olympic torch. The Drill presentations by the middle school students were equally impressive. The Class VII girls’ aerobics, Class VII boys’ wand exercise, Class VIII girls’ yoga asanas and the Class VIII boys’ pyramid formation were greatly admired and applauded by the gathering.</p>
						<p style="text-align:justify;">Students who had excelled in various sporting events were honoured with medals presented by the Principal and the Chief Guest. The Chief Guest, Mr. V. Devarajan, congratulated the school on its achievements at the state, national and international levels. Encouraging the young athletes,  he delivered an inspiring address, reminding students that multiple failures pave the way to success and urged them to embrace the motto, “Will is stronger than skill”. His inspiring words were met with enthusiastic cheers from the audience. </p>
						<p style="text-align:justify;">The Topaz House won the cup for the best March Past. The Emerald House was declared the overall champions for Sports Day 2026. The Topaz House was the runners-up. The memorable celebration concluded with the National Anthem.</p>
