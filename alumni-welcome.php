					<div class=" col-xs-12 col-sm-12 col-md-12">
						<p style="text-align:justify">On April 26, 2021, a remembrance event was organised by Project Sambandh and the schoolmates of Capt. Bhaskar at the premises of P.S. Senior Secondary School, Mylapore. To adhere to the COVID protocols, the event was restricted to limited participants.</p>
						<p style="text-align:justify">Representing the family of Capt. Bhaskar were Mrs. Chitra and Mr. Raghu (sister and brother-in-law of Capt. Bhaskar). The P.S. Senior Secondary School was represented by Dr. Revathy Parameshwaran and Mr. Sivakumar (Principal and Vice Principal). Mr. Rajaram and Mr. V.V. Ramanan, classmates of Capt. Bhaskar, represented the 1985 batch, Mr. Srivatsan Parthasarthy and Col. Vembu Shankar, SC, of the 1993 batch represented the other alumni of the school, while Mr. Aryan of the 2021 batch represented the present student community. Two Non Commissioned Officers of the Army Service Corps represented the Indian Army at the solemn event.</p>
						<p style="text-align:justify">The event started with a specially recorded bhajan rendered by the US-based Ms. Harini (1993 batch). Welcoming the invitees, Col Shankar, an Indian Army Veteran and founder of Project Sambandh, spoke about how the connect with the NOK of Kin of Capt. Bhaskar was established and how the course mates and batchmates of Capt. Bhaskar had relived his memories through anecdotes and photos. Messrs Rajaram and Ramanan shared their personal experiences with Bhaskar, highlighting his football skills and academic prowess.</p>
						<p style="text-align:justify">Dr. Revathy Parameshwaran lauded the efforts of the 1985 batch of the school to organise such an event which only highlights the strong bonds of friendship amongst the alumni. She saluted Capt. Bhaskar and offered her respects to his family with the hope that the legacy of Capt. Bhasakar and Anand will continue to inspire the future generations of students from the school. The Principal conveyed her appreciation to Project Sambandh and the efforts of Col. Shankar.</p>
						<p style="text-align:justify">To perpetuate the memory of Capt. Bhaskar and Anand, Mr. Rajaram, on behalf of the 1985 batch, announced the establishing of an endowment prize for those students who join the Indian Armed Forces immediately after the completion of their school academics. In this regard, the batch honoured Mr. Aryan, who has qualified to join the 146th course of National Defence Academy in June 2021, with a cash award.</p>
						<p style="text-align:justify">Mr. Raghu fondly remembered Bhaskar as an energetic and enthusiastic family member. He highlighted the efforts of Project Sambandh and how such bonds are important. He hoped that more students from P.S. Senior Secondary School would choose armed forces as a career.</p>
						<p style="text-align:justify">The event concluded with floral homage to the photograph of Capt. Bhaskar and the tolling of Shrivatsa, the Bell of Gratitude and Remembrance, installed by the 1993 batch on the occasion of its Silver Jubilee reunion.</p>

