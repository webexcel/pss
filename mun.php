						<p style="text-align:justify;"><b>Clarion PS MUN 2025</b></p>
						<p>The 12th edition of Clarion PS Model United Nations 2025 was held on the 27th and 28th of October, guided by the motto “Sreyash Sadhanam”, translating to “Ultimate Excellence.”</p>

						<p>Year after year, the conference stands as a premier platform where delegates from across the city gather to demonstrate their excellence in debate, diplomacy, and lobbying.</p>

						<p>Day One of the conference was inaugurated by our esteemed alumnus and Secretary-General, Mr. Aashrith S. Narayan, and graced by the presence of our Principal, Dr. Revathy Parameswaran. The conference featured eight committees, a distinguished Executive Board, and enthusiastic participation from over twelve city schools.</p>

						<p>Day Two of the event was conducted online due to inclement weather, yet it remained an engaging and enriching experience for both participants and the Executive Board—making PSMUN 2025 the first-ever hybrid edition in its history.</p>

						<p>The Valediction Ceremony, held on the 29th of October, was graced by Ambassador S. Swaminathan, a distinguished former officer of the Indian Foreign Service, and our Correspondent, Shri P. S. Prabhakar. They shared their words of wisdom and felicitated the award recipients, marking a fitting conclusion to yet another successful edition of Clarion PS Model United Nations.</p>					
												
