					    <p><b>TEACHERS’DAY CELEBRATION AND FELICITATION TO THE PRINCIPAL</b></p>
						<p>P.S. Senior Secondary School, Mylapore, hosted a memorable Teachers’ Day celebration on September 8, 2025, at Srimathi Narayani Ammal Kalyana Mandapam, Jeth Nagar, marking a historic milestone—the school’s Golden Jubilee along with the felicitation of its Principal, Dr. Revathy Parameswaran, who recently received the coveted National Award for Teachers 2025 from Smt. Droupadi Murmu, Honourable  President of India.</p>

						<p>The event began with a warm welcome to more than 50 of the school’s former teachers, returning to the place “where their wisdom shaped countless young minds.” It was day of memories for most members who had served the school at various capacities decades ago and were meeting each other after long years. Adding grandeur to the evening was a soul-stirring concert by Shri Praveen Pandit, alumnus of the school, which set the tone for the celebrations.</p>

						<p>A special highlight was the felicitation of Dr. Revathy Parameswaran by the school’s former principals  Smt. Vijayalakshmi Srivatsan and Smt. Lakshmi Srinivasan, who were the recipients of National Award in 2002 and 2013 respectively. This rare gathering of distinguished, award-winning educators made the occasion truly significant. Shri K.S. Gopalakrishnan, President of the P.S. Educational Society, Correspondent Shri P.S. Prabhakar, and several former teachers joined in felicitating the Principal. Former teachers also conveyed their warm wishes and fondly recalled their cherished memories, 
