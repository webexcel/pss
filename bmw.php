				<p><b>The unforgettable trek experience - Brahmatal, Uttarakhand</b></p>
				<p>The trek to Brahmatal was organised by the school in partnership with Indiahikes as 
				part of the Outdoor Learning Program. The trek team comprised of 35 students and 4 
				teachers - The Principal, Dr. Revathy Parameshwaran, Mr. Gopalakrishnan from the 
				Math department and Mr. Thirumurugan and Mrs. Aruna from the PT department. </p>
				<p>After deciding to trek to Brahmatal Peak, the team started preparing to have physical fitness for the long trek. Fitness session with stretches, cardios, mock- trek to local hills, strength training, psychological strength etc.  were arranged on a regular basis for almost two months before the actual trek under the guidance of the Principal with enthusiastic support from teachers.
				Lasting for eight days from the 27th of April to the 4th of May, the 4-day trek to the 
				summit at 12,250ft for a breath-taking view of an alpine lake, Brahmatal was truly one 
				for the soul to cherish.</p> 
				<p>This trip was unique in seeing students from three grades - 10, 11 and 12 participating in a trek, and further more in creating lasting bonds with nature and students of different ages. 
				An achievement it was, that the entire team reached the summit with no one left behind, as this had not happened in  any previous school trek. 
				The students experienced pristine nature in all four campsites, Nanda Ghunti, Trishul and Mt. Kamet (India’s Third Highest Peak) and Roopkund Trek Route  including the 
				basecamp Lohajung. </p>
				<p>They also understood the perils of human consumerism and 
				global warming that takes a toll on the mountains. During the Green trails green 
				sweeps, the team managed to collect and segregate 35kgs of littered waste and this 
				brought an eco-friendly mindset in many. </p>
				<p>The trip was a spiritual one as the altitude and serene silence helped to connect with oneself 
				and summit the inner mountain of possibility. The trip had its befitting end with 
				a sight of the holy Ganga Maa and the aarti offered to her in Rishikesh</p>
