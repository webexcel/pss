					    <p><b>Menstrual Health Awareness Programme</b></p>
						<p>A programme for improving menstrual health awareness among middle school and high school students was conducted from 15 April 2025 to 22 April 2025 by the students of class 12. The girls of the student council organised the programme, and 12th-grade biology students volunteered to explain the concepts. </p>

