					<p><b>Scintillations 2024</b></p>
						<p>P S Senior Secondary school hosted the inter school cultural meet Scintillations’24 on the 1st and 2nd July 2024. About 20+ competitions including submission events were thrown open to city schools in which over 20 schools participated with enthusiasm and fervour. The inauguration was held on 1st July 2024 at TAG Dakshinamurthy auditorium in which the school principal Dr Smt Revathy Parameshwaran addressed the students and declared Scintillations’24 open. The various events like music, dance, TED talk, comic book designing , IPL auction, futsal, drew the best talents from the city school students. The valediction ceremony for the same was held on 2nd July 2024 at 2 30 pm. The chief guest was Palghat Ram Prasad , a practising Carnatic musician and a scholar of Economics from the Harvard University. The Chief Guest spoke on preserving one's own culture and asked the students to go back to their roots. Vidya Mandir Mylapore were declared the winners and PSBB K K Nagar were declared the runners up in Scintillations’24.</p> 					
