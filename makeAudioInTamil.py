# Install once:
# pip install gTTS

from gtts import gTTS

# === Your Tamil text ===
tamil_text = """
எங்கள் பள்ளி ஆப் வழிகாட்டிக்கு வரவேற்கிறோம்.
படி 1: வாட்ஸ்அப் குழுவில் பகிரப்பட்ட இணைப்பை கிளிக் செய்யவும்.
படி 2: ஆப்பை நிறுவி, எங்கள் பள்ளியின் பெயர் மற்றும் லோகோவை பார்த்து உறுதிசெய்யவும்.
படி 3: ஆப்பை திறந்து உங்கள் பதிவு செய்யப்பட்ட மொபைல் எண்ணை உள்ளிடவும்.
படி 4: சரியான எண் கொடுத்தால், சேர்க்கை எண்ணை OTP ஆகக் கேட்கும்.
படி 5: உள்நுழைந்த பின், டாஷ்போர்டு பக்கத்திற்கு செல்லலாம்.
அங்கிருந்து அனைத்து வசதிகளையும் பார்க்கலாம்.
"""

# === Generate Tamil audio ===
tts = gTTS(text=tamil_text, lang='ta')
tts.save("narration_tamil.mp3")

print("✅ Tamil audio saved as narration_tamil.mp3")
