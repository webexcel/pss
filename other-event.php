					<p><b>‘OPTICA’ - A session on Ray Optics by IIT Madras</b></p>
					<p>IIT Madras collaborated with our school to demonstrate experiments related to ray optics in their session “Optica”. Students of class 12 A, 12 B and 12 C had the opportunity to watch and perform 8 different experiments related to ray optics. The experiments focused on various properties of light like reflection, refraction, diffraction, TIR and a lot more.  </p>
					<p>It was an exciting and “illuminating” experience to see the theoretical concepts applied directly in practical experiments that can be easily replicated. The experience enhanced students’ connect with the subject. Some of the experiments listed below were definitely eye-openers.</p>
					<h4>Spectrum of light:</h4>
					<ul>
					<li>1.	Mixing of light:</li>
					<p>The three main primary colors are red, green, and blue. All the other colors are formed by combining these.</p> 
					<li>2.	How objects show color:</li>
					<p>Objects absorb the light rays and reflect light of certain a wavelength. This is the color of that object. Black doesn’t reflect light at all while white reflects all the colors. (In temples, the pathway is painted white as it doesn’t become hot on a sunny day)</p>
					</ul>

					<h4>Path of light:</h4>
					<ul>	
					<li>1.	Rectilinear propagation of light:</li>
					<p>Light moves in a straight path (homogenous mixture).</p>
					<li>2.	Reflection through a plane mirror:</li>
					<p>Angle of incidence = angle of reflection</p>
					<li>3.	Convergence and divergence of light through spherical mirrors:</li>
					<p>Convex mirror: diverging</p>
					<p>Concave mirror: converging</p>
					<p>The path of light was seen through a colloidal solution (Dettol solution)</p>
					</ul>

					<h4>Reflection- an overview:</h4>
					<ul>
					<li>1.	TIR (total internal reflection):</li>
					<p>When the angle of incidence is greater than that of the critical angle, light rays get reflected continuously inside the second medium.</p>
					<p>Applications: optic fiber, diamond making, etc</p>
					<li>2.	Invisibility:</li>
					<p>When an object is kept in a medium of the same refractive index as itself, it does not get reflected (glass rod in water can be seen but in oil it cannot be seen).</p>
					<li>3.	Periscope:</li>
					<p>It is device that is used to view objects at a higher height that the eyelevel (it is used in submarines to see the surface above the water).</p>
					<p>It works on the principle of multiple reflections.</p>
					</ul>
					<h4>Dispersion of light and telescope:</h4>
					</ul>
					<li>1.	Rainbow:</li>
					<p>White light constitutes the seven colors of VIBGYOR.</p>
					<p>When light passes through a rain drop, it first gets dispersed into the colors of a rainbow. Then it undergoes internal reflection after which it is finally refracted out of the drop.</p>
					<p>Red has the highest wavelength of around 632 nm and can be seen through a longer distance than the other colors.</p>
					<p>Although the rainbow is a full circle, we can see only half of it as the other half gets submerged under the horizon.</p>
					<li>2.	Telescope:</li>
					<p>It consists of two lenses-</p>
					<p>The objective focuses objects at infinity at the focus as a sharp point image.</p>
					<p>The eyepiece enlarges this image, and the eye can see the object distinctly.</p>
					</ul>

					<h4>Polarization and diffraction:</h4>
					<ul>
					<li>1.	Polarizer:</li>
					<p>This is a plane used to transfer light along only one direction (no light passes through polarizers directing light in different directions).</p>
					<p>But when a plate of different is kept between them, some light gets transferredand the plate is seen.</p>
					<li>2.	Grater:</li>
					<p>It has a plane with lines of light (splits) on its surface that splits white light when it passes through it. These are either parallel straight lines or concentric circles.</p>
					<p>This principle is used in X-ray diffraction (depending on the wavelength of light read through the splits, the image is formed).</p>
					</ul>
					<h4>Solar cell:</h4>
					<p>It converts solar energy to electrical energy. The amount of energy produced depends on the area of light absorbed.</p>
					<p>Sun follower- it is an addition to the solar panel where the sensors help the panel to follow the sun from sunrise to sunset. This increases the amount of energy produced.</p>

					<h4>VR (virtual reality) box:</h4>
					<p>There are twovideos that are focused as one when we view them. The videos are either recorded or give a 360-degree view. </p>
					<p>The 360-degree view is aided with the help of two sensors to sense the direction movement of the head. A 360-degree image is formed by stitching various images together.</p>
					<p>Overall, this learning experience based on experiments has helped in better comprehension of the concepts. The session has provided a very strong foundation in ray optics for the students of Class 12.		</p>

