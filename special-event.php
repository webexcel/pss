						<p><b>PS AMBLE 2025</b></p>
						
						<p>P. S. Senior Secondary School successfully hosted PS AMBLE 2025, its flagship inter-school commerce fest, on July 17 and 18. The second edition of this vibrant event welcomed over 250 students from 23 schools, building on the strong participation of 17 schools in its inaugural year.</p>

