					<p><b>PS AURIX 25 – Inspiring Young Minds through Science and Innovation</b></p>
					<p>PS AURIX 25, the annual inter-school science fest, was successfully conducted on 17th and 18th July 2025. This flagship event served as an engaging and inspiring platform for students from Classes 
					9 to 12 to explore scientific ideas beyond their textbooks and experience the true essence of science through innovation, experimentation, and inquiry.</p>
					<p>The name AURIX encapsulates the spirit of the fest:</p>
					<ul>
					<li>* A – Astronomy</li>
					<li>* U – Universe</li>
					<li>* R – Research</li>
					<li>* I – Innovation</li>
					<li>* X – eXperiments</li>
					</ul>
					<p>The two-day event commenced with a compelling guest lecture by Dr. Srikanth Vedantham, Professor at IIT Madras, on the topic “Taking Science to the Real World Using Engineering Design.
					” His insights set the tone for a fest centered on practical application and creative exploration.</p>
					<p>This year’s edition witnessed enthusiastic participation from over 500 students representing 20 schools across Chennai.
					With a dynamic array of events such as Clues of Cosmos and Riddle Hunt, students were encouraged to delve into complex scientific ideas, employ critical thinking, and collaborate in solving challenges rooted in real-world problems.</p>
					<p>Each event was meticulously designed to foster experiential learning and emphasize the real-world relevance of science—elements often missing in traditional academic setups. The fest struck a perfect balance 
					between competition and collaboration, leaving a lasting impression on both participants and attendees.</p>
					<p>* Students of Class 9 and 11 showcased their creativity through innovative science exhibits.</p>
					<p>* Students of Class 12 took the lead in organizing and managing the events, demonstrating leadership and teamwork.</p>

					<p>The fest concluded with a thought-provoking valedictory lecture by Dr. Ajith Pai, renowned cancer surgeon, on the “Application of Robotics in Cancer Treatment.
					” His talk offered a glimpse into the future of medical science and its transformative potential. The event wrapped up on a high note, with students, teachers, 
					and guests leaving with renewed enthusiasm for science and a wealth of new knowledge and inspiration.</p>
