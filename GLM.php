						 <p id="2"><b>GLPSS Convocation ceremony 2025</p>
							<p>The convocation of the 13th batch of GLPSS took place on April 25th 2025 at the Great Lakes Institute of Management, ECR. Around seventy-two students of the Commerce stream (2025-26) received graduation certificates upon successful completion of the program. Mrs. Pratima Lakshmanan, Head - Strategic Initiatives, delivered the welcome address, setting the tone for the programme following the invocation and lighting of the lamp. </p>
							<p>The graduation address was delivered by the Chief Guest, Mr. SundaraBashyam Reddy, Managing Director of Accenture Operations following which he distributed the certificates to the students. Winners of the entrepreneurship competition were also awarded prizes. Mr. Suresh Ramanathan, Dean of Great Lakes Institute of Management and members of the P.S Senior Secondary School management – Mr. P.S Prabhakar, Correspondent, Dr. Revathy Parameswaran, Principal and Mrs. Padmasree Nirmalkumar, Vice Principal were present. The Best Student award was bagged by Gadi Bhargav Krishna, for discipline and punctuality. The convocation was held on the last day of the five-day residential camp at the Great Lakes Institute campus. The camp consisted of insightful simulations, intense debates, presentations and even an outdoor team building activity. Mr. Antony, Program Manager, GLPSS School Program delivered the vote of thanks. The convocation was followed by High Tea, which served as a fitting close to the ceremony.</p>
