						<p><b>Workshop on Understanding and teaching children with Learning Difficulties</b></p>
							<p>A workshop to enlighten and empower parents and teachers with strategies to identify and address the needs of  childrenwith  specific Learning difiicultieswas organized by our school in collaboration with Kalvi foundation.</p>
