							<p><b>Primary Day Celebrations</b></p>
							<p>Resplendent Extravaganza, our School’s Primary Day celebration was held on 3rd February 2024 in the school premises. The theme of this year’s event focussed on the harmonious convergence of nature and culture. The chief guest was Dr. V.R. Devika, a distinguished author, educationist, and the founder of, ‘The Aseema Trust’. In her enlightening address, Dr. V.R. Devika elaborated on the principles of ‘Sathya’ and ‘Ahimsa’ championed by Mahatma Gandhi urging the students to embody these values in their lives. 
The programme included Bhajans, a mesmerizing tableau showcasing different seasons, and a choir on ‘rainbow’ by classes 1 and 2 students. This was followed by an English play on the inspiring life of Amrita Devi Bishnoi-Saviour of trees which was followed by yet another choir performance on the conservation of trees. The programme concluded with a Tamil dance drama that encapsulated the essence of the life and teachings of the revered woman Alvar, ‘Andal’. The Principal extended heartfelt gratitude to the parents for their invaluable support and cooperation in making this event a grand success.</p>
							
