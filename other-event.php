					    <p><b>P.S. Senior Students take initiative for a Cleaner Coast</b></p>
						<p>The students of P.S. Senior Secondary School, Mylapore had undertaken a beach clean-up drive
						along the Marina coast on the 12th of April as part of the School’s community service initiative.</p>
						<p>The event, coordinated by the School Pupil Leaders - Abhinav Saran K V and M M Liban
						Reyhan, saw over 150 students of Class XII and teachers participate in the event - collecting
						nearly half a ton of waste. Equipped with masks and gloves, students began collecting waste
						from the shore at 6:00 AM and continued their efforts for two hours. The drive was conducted as
						an effort to bring in awareness among the student community and the public at large on the
						importance of a clean environment and social responsibility.</p>
						<p>While the Greater Chennai Corporation has been regularly taking up the cleaning at the beach
						area, there seems to be a lot of debris unattended over frequent intervals. Activities like this help
						the civic bodies with augmented efficiency through community participation. The school plans to
						continue such initiatives regularly to instill a sense of civic responsibility among students.	</p>					
