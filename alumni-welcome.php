						<p><b>Alumni meet – Saturday the 23rd December 2017.</b></p>
						<P>December 15, 2017 - December 23, 2017</p>
						<P>Dear Alumni, 
						We welcome you all to ‘Back to School’ Alumni meet on Saturday the 23rd December 2017.
						Hearty Welcome to one and all and to the ‘Class of 92’ for their Silver Jubilee reunion.</p>
						<P>Principal</p>
						<P>Memorial service for Captain Bhaskar our proud alumnus.</p>

						<P>Capt. J. Bhaskar an alumnus of P.S Senior Secondary School (Class of 1985) and the National Defence Academy (Golf Squadron/74 Course) got commissioned in the Indian Army in 1989.</p>
						<P>Soon he saw active operations in Sri Lanka as part of the Indian Peace Keeping Force. On completion of his attachment with the 4 JAT, Capt. Bhaskar served with the Army Service Corps in NE India and later in Pathankot.</p>
						<P>On April 26, 1994, he was tasked with the opening of the convoy route between Manali and Leh where he met with an accident and died while in service. Such casualties are termed as Physical Casualties in the Indian Army.</p>
						<P>The Next of Kin (NOK) of physical casualties have to face immense financial, social and emotional challenges. Over a period of time, the bond between the NOK and the Army also weakens due to various factors.
						But, in a welcome development and after nearly three decades of effort, a connect with the NOK of Capt. Bhaskar was established this March.</p>
