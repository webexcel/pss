				<p><b>Trekking - Outdoor learning program near Banagalore</b></p>
				<p>I still remember when my tent-mates and I first stepped into our tent, feeling doubtful that we could make it. Living without the comforts of an urban home seemed impossible at first. But, spoiler alert—we did it. We made it through, safe and sound, and returned with a
				deeper appreciation for everything we have back here.
				We were set to trek Channarayana Durga, a stunning mountain range with an impressive height of 3,730 feet. 
				When I first learned that this was the hill we would soon climb, my heart skipped a beat, wavering in doubt 
				about whether we could do it.</p>
				<p>The rest of the first day was spent engaging in various activities. One thing the team
				emphasized was reflection—reflecting on our activites to ensure that we returned to our cities having learned something meaningful, not just having had fun. My favorite activity, however, was stargazing. After a night walk, we were treated to an incredible view of the
				night sky. In all my fifteen years, I had never seen so many stars. Everywhere I looked, I could spot stars, satellites, and even a few planets. We then applied our knowledge of these celestial bodies, learning to differentiate between them and identify the four cardinal
				directions. It made me realize how light pollution has affected the urban night sky, robbing us of the privilege of seeing such brilliant stars</p>			
