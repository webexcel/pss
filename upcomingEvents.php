						<p style="text-align:justify">P. S. Senior Secondary School has a long and illustrious history of excellence. Here are a few milestones in its journey so far:school conducts several programmes to identify and nurture talent in Music, Dance, Drawing, Painting, and Crafts.</p>

P. S. Educational Society was founded in 1905 by Brahmasri Pennathur Subramania Iyer, who served as a solicitor, and also the commissioner for Mylapore from 1890 to 1901. On his passing, he bequeathed his entire properties to P. S. Charities, and founded P. S. Higher Secondary School on RK Mutt road, in the heart of Mylapore
June, 1976:  P. S. Senior Secondary School (CBSE) was established as a unit of the P. S. Educational Society. Shri. C. R. Pattabiraman served as the founder president, and Shri. P. C. Sekhar as the first correspondent of the school
1982: First batch of class XII students
1986: The school was granted permanent affiliation by CBSE
1990: K. Alamelu was conferred the National Award to Teachers by Government of India, presented by the President of India. This was followed by Vijayalakshmi Srivatsan (2002) and Lakshmi Srinivasan (2013) receiving the same award.
1995-96: Sumankar Shankar became the first student from the school to represent the country in International Olympiads, winning the silver medal at the International Olympiad in Mathematics held in Toronto, Canada. Since then many students from P S Senior have represented the country in international Olympiads in Mathematics, Physics, Chemistry, Biology, and Informatics Practices, and have won gold, silver and bronze medals.
1996: G. Prasanna scored All India Rank 1 in the IIT Joint Entrance Examination
2012: P. S. Temple Green Vidyashram, a sister concern of P S Senior Secondary School, was launched in Oragadam
2012-2015: Installation of smart boards in all classrooms (from I to XII) to promote technology-enabled learning
2012-2015: Conferred the International School Award by British Council
2015: Digital Library was inaugurated
2016: State-of-the-art studio facility was launched to share teaching and learning resources with PS Temple Green Vidyashram, Oragadam
2016: Gymnasium was established at the school
