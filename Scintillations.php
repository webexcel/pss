					<p><b>Scintillations 2025</b></p>
						<p>Scintillations, the school’s annual interschool cultural fest, returned this year  on the 27th and 28th June with more excitement than ever.</p>
						<p>Over 650 students from 30+ schools, participated in what one would call the mega cultural event in school circuits.</p>

						<p>Our principal, Dr. Smt. Revathy Parameswaran inaugurated the event on 27th June. The theme of this year was ‘the Golden Era of Music’. 15+ events were conducted that tested students' creativity, quick thinking, memory, articulation etc. From music and dance to ted talk and quizzes, every moment was packed with energy and zing.</p>

						<p>The school had the honor of hosting Ms Sriranjani Santhanagopalan, renowned Carnatic musician, as the Chief Guest for the Valedictory function. She congratulated the winners and spoke on the amazing opportunities available to the students.</p>
						<p>Tasmai from Vidhya Mandir Mylapore clinched the Mr. Scintillator title and bagged Nothing Phone worth ₹25,000. The chief guest distributed the prizes to winners of various events. Chettinad Vidhyashram bagged the winners position followed by PSBB in the runner up slot.</p>

						<p>Scintillations 2025 truly lived up to its name, sparkling with talent, spirit, and unforgettable memories.</p>
