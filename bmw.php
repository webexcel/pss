							<p><b>Manali Trek 2024</b></p>
							<p>The students of Science Group accompanied by Principal Ma'am, Gopalakrishnan Sir, Ramraj Sir and Sridivya Ma'am boarded the flight to Chandigarh at around 10:30 am on the 24th of April on an exciting trekking trip to Manali. On reaching Chandigarh, they took a bus to the base camp and reached by midnight on the same day. The India Hikes Team, consisting of Faizan, Jagdeesh, Abhilasha, Dev, Chaubeyram and Abhishek briefed the students on how the whole experience will pan out. India Hikes team conducted many team building exercises to make the trekking experience fun and enjoyable while helping the students connect with nature.  The first destination of the trek was The Gowrishankar Temple. It is believed that the Pandavas had built this temple in just one night using a single stone. The next destination was the Crystal Waterfalls. The second-highest point of the trek was the journey to Kais Dhar that involved a 3-hour long journey by car and then a 3-hour long hike along an almost flat terrain. On the last day, the group went on a trek to Chambagarh Top to experience the sunrise and the 360-degree view of the surroundings from there. The view was surreal and the sight of the reflection of the rising sun on the Himalayas couldn't be described using words.  Towards the end of the trek, a few groups of students came up with wonderful poems, 
								skits and essays describing the entire trekking experience. It was a wonderful learning experience for the students.
