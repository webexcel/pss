						<p style="text-align:justify">Progress is measured by milestones. Goals can become a ritual or a fetish, but in the right measure they can give us some much needed reference points. P. S. Senior Secondary School has had a long and illustrious history of excellence. Here are a few milestones that can act as reference points in its journey so far and for the miles to be traversed:</p>
						<ul>
						<li>1905 : P. S. Educational Society was founded in 1905 by Brahmasri Pennathur Subramania Iyer, who served as a solicitor, and also the commissioner for Mylapore from 1890 to 1901. On his passing, he bequeathed his entire properties to P.S. Charities, and founded P. S. Higher Secondary School on R.K.  Mutt road, in the heart of Mylapore.</li>
						
						<li>1976 :  P. S. Senior Secondary School (CBSE) was established as a unit of the P. S. Educational Society. Shri. C. R. Pattabiraman served as the founder president, and Shri. P. C. Sekhar as the first correspondent of the school.</li>
						<li>1982 : First batch of class XII students to pass out of the school.</li>
						
