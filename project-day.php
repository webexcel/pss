					<p><b>Math Week Celebrations</b></p>
					
					<p>The Department of Mathematics feel proud  in celebrating Ramanujan Math day in a wonderful way to highlight and  honor the contributions of Srinivasa Ramanujan ,one of the greatest mathematicians of all time. The programs was conducted from 18 /11/2024  to 26/11/2024 across classes 5 to 11.</p>
					<p>Class 5 : Poster Making Contest on the assigned topic “ MATHEMATICS IN MUSIC, ART & ARCHITECTURE”.</p>
					<p>The Posters done by our students beautifully portrayed and artfully depicted the concepts.</p>
					<p>The posters were eye catchy and brought out the creative thinking of the budding minds. There were ingenious sketches that described the role of Math in real life which proved to be inspiring in correlating the implementation of the concepts.</p>
					<p>Students exhibited  their talent while enjoying the work of  making the poster.</p>
					<p>Class 6 : Students actively took part in Sudoku which is a logic- based combinatorial placement puzzle. It helps the children in boosting their concentration , teaches them patience, nurtures a healthy mindset and enhances spatial reasoning.</p>
					<p>Class 7 : The contest was based on “ TEACHING LEARNING MATERIALS ( TLM)</p>
					<p>Students displayed their aptitude and ability by demonstrating Two dimensional models involving ambitious concepts with a brilliant flair. Some of the notable concepts exhibited by the students were Golden Ratio , Pythagoras theorem, Trigonometry etc. Every model was illustrated with real life applications and with intricate details which provided significant learning takeaways from the event.</p>
					<p>Class 8: The given topic for the students was “ MODEL MAKING “ </p>
					<p>Participated students showcased their mathematical models , displaying physical representations like projectiles , concepts in three dimensional geometry and many more visualizations of mathematical concepts.</p>
					<p>Class 9 : Students were engaged in the activities using “ GEOGEBRA” </p>
					<p>These activities involved interactive demonstrations and simulations to illustrate mathematical principles and their relationships.</p>
					<p>Class 11 : Senior secondary students was given  an opportunity to solve mathematical problems from the past years of Regional  mathematical Olympiad problems . The process of solving will help the students  to  develop the  critical thinking and  analytical skills.</p>
					<p>Overall ,the variety of activities organized by each class demonstrate an exhaustive approach to celebrating Ramanujan Math day.</p>
					<p>These activities not only engaged students with mathematics but also promoted their team work, creativity and a deeper appreciation for the subject.</p>
