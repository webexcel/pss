						<p><b>Golden Jubilee Celebrations Chess Tournament</b></p>
						<p>P.S. Senior Secondary School successfully hosted a State-Level Chess Tournament on Sunday, August 3rd, as part of its Golden Jubilee celebrations. The event was held on the school campus and organised in collaboration with KQ Chess Academy.
						<p>The tournament featured three categories:</p>
						<ul>
							<li>Event 1: Unrated players under 11 years of age</li>
							<li>Event 2: Unrated players aged 12 and above</li>
							<li>Event 3: All FIDE-rated players</li>
						</ul>
						<p>A total of 450 participants took part in the tournament, including 182 FIDE-rated players, making it a highly competitive and well-attended event. In Events 1 and 2, trophies and medals were awarded to the top 20 players. In Event 3, a total of ₹35000 was awarded as a cash prize alongside trophies for the winners, with the first-place cash award of ₹10,000. </p>
						<p>Additional prizes were also presented in special categories, including Women, Veterans, and Physically Challenged players, ensuring inclusive recognition across the board. The valedictory function was graced by Grandmaster Debashis Das, the school's correspondent, Mr. P.S. Prabhakar, the Principal, Dr.(Mrs.) Revathy Parameshwaran and the Vice Principals, Mr. Sivakumar and Mrs. Lakshmi. </p>
						<p>The event was a grand success, celebrating the spirit of chess and fostering sportsmanship among players of all ages</p>
					
