							<p>Resplendent Extravaganza, our School’s Primary Day celebration was held on 1st February 2025 in the school premises. This year’s event started with Orchestra showcasing the talents of our young budding carnatic singers. This was followed by a valuable and mesmerising speech of the Chief Guest Dr. K R Seethalakshmi (former Principal of QMGCW).
							The programme included a tableau emphasising the importance of farming, the backbone of our country and dances portraying the celebrations of harvest festivals like pongal, makr sankranti, kite festival, nuakhai, tarpa, and warli ,which was performed by students of classes 1 & 2. It was followed by a bi-lingual dance drama on Endangering of Frogs and the measures to be taken to conserve them. Other programmes included fusion dances of the world, a skit in English about the joy of reading books, followed by a Tamil play emphasising the sobriquet-Mayilaiye Kayilai-Kailaye Mayilai, and a Bharatanatyam recital glorifying mother India. The programme ended with a rhapsody rendition of a Bharathiyar song.</p>
