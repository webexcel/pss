						<p style="text-align:justify">Brahmasri Pennathur Subramanya Iyer was born in March, 1860 in a middle class family at Chittoor. He was a man of great courage, dedication and generosity. His graceful demeanour  and elegance in manners made him stand out. In 1890, he was made the Commissioner for the Mylapore Division, a seat he retained till his death in 1901. It was at his instance and through his influence that the underground drainage works were done in the Mylapore Division, replacing the open drains that had existed before as a hotbed of infections of various kinds.  He thought that the best use he could make of his wealth was to utilise it for the spread of knowledge and education of the upcoming generations. This led to the formation of the  P. S. Charities which has  expanded its service in the cause of education and stands glorious after 100+ years. He bequeathed all his property towards P.S. Charities.</p>

