					<p><b>TWO-DAY TRAINING CAMP FOR STUDENTS IN THE STEM LAB </b></p>
					<p style="text-align:justify;">A two day training camp was conducted in the STEM lab for students of Class 11.It was an interesting and enjoyable learning experience for students. The training camp started off by introducing the basics of electricity and electronics (direction of flow of charges, capacitors,  resistors,  serial and parallel circuits) and moving on to Robotics. The training camp gave the students an opportunity to put whatever they had learnt as theory into practise. As a hands-on activity, on the first day, students created simple paper circuits based on the theory session. </p>  
					<p style="text-align:justify;">On day 2, students were introduced to micro-controllers like Arduino and ERS. Students learnt how to interface different sensors with the Arduino board, program the micro-controller and create a smart device. Science, technology, engineering and computational thinking were at play in creating these smart devices and students could appreciate the role of each of these fields in equal measure. This session was the highlight of the two day workshop as students turned into makers.  Students simulated the working of traffic lights and smart street lighting using Arduino Uno. Using the robotics tool kit, students created a cable car and a remote controlled car. Overall, the training was a wonderful experience for students to hone their skills to become creators and innovators while enjoying science in action. </p>

